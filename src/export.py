import numpy as np
import pandas as pd

import config as C


def station_table(stations, hourly_panel, backtest_preds, segments_df):
    hp = hourly_panel
    agg = hp.groupby("station_key").agg(
        total_departures_year=("salidas", "sum"),
        annual_net_imbalance=("flujo_neto", "sum")).reset_index()

    # per-station mae/coverage by window from backtest.
    bp = backtest_preds.copy()
    bp["abs_err"] = (bp["necesidad"] - bp["need_p50"]).abs()
    bp["cov"] = (bp["necesidad"] <= bp["need_p90"]).astype(float)
    perf = bp.groupby(["station_key", "ventana"]).agg(mae=("abs_err", "mean"),
                                                       coverage=("cov", "mean")).reset_index()
    perf = perf.pivot(index="station_key", columns="ventana", values=["mae", "coverage"])
    perf.columns = [f"{a}_{b.lower()}" for a, b in perf.columns]
    perf = perf.reset_index()

    out = (stations.merge(segments_df, on="station_key", how="left")
                   .merge(agg, on="station_key", how="left")
                   .merge(perf, on="station_key", how="left"))
    for col in ["mae_am", "mae_pm", "coverage_am", "coverage_pm"]:
        if col not in out.columns:
            out[col] = np.nan
    return out[["station_key", "station_ids", "name", "lat", "lng", "segment", "segment_action",
                "total_departures_year", "annual_net_imbalance",
                "mae_am", "mae_pm", "coverage_am", "coverage_pm", "is_relocation"]]


def predictions_window_table(backtest_preds, forecast_preds):
    b = backtest_preds.copy()
    b["mode"] = "backtest"
    b["need_actual"] = b["necesidad"]
    b["covered"] = (b["necesidad"] <= b["need_p90"]).astype(int)
    b["departures_pred"] = b["salidas_media_4sem"].round(1)
    b["rain"] = b["hubo_lluvia"].astype(int)
    b = b.rename(columns={"ventana": "window"})
    cols = ["station_key", "date", "window", "mode", "need_p50", "need_p90", "need_actual",
            "baseline_p50", "baseline_p90", "covered", "departures_pred", "rain"]
    b = b[cols]
    if forecast_preds is not None and len(forecast_preds):
        f = forecast_preds.rename(columns={"ventana": "window"})[cols]
        return pd.concat([b, f], ignore_index=True)
    return b


def routes_table(trips, top=200):
    arr = trips[trips["is_arrival"]].copy()
    arr["dur_min"] = (arr["ended_at"] - arr["started_at"]).dt.total_seconds() / 60.0
    r = (arr.groupby(["start_station_key", "end_station_key"])
         .agg(trips=("ride_id", "size"), avg_duration_min=("dur_min", "mean"))
         .reset_index().sort_values("trips", ascending=False).head(top))
    r["avg_duration_min"] = r["avg_duration_min"].round(1)
    return r


def weather_effect_table(window_panel):
    wp = window_panel.copy()
    rows = []
    for (sk, win), g in wp.groupby(["station_key", "ventana"]):
        dry, rain = g[~g["hubo_lluvia"]], g[g["hubo_lluvia"]]
        if len(dry) == 0 or len(rain) == 0:
            continue
        ad, ar = dry["necesidad"].mean(), rain["necesidad"].mean()
        pct = (ar - ad) / ad * 100 if ad > 0 else np.nan
        rows.append({"station_key": sk, "window": win, "avg_need_dry": round(ad, 2),
                     "avg_need_rain": round(ar, 2), "pct_change": round(pct, 1) if pct == pct else None,
                     "n_dry": len(dry), "n_rain": len(rain)})
    return pd.DataFrame(rows)


def _to_js(name, df):
    d = df.copy()
    for c in d.columns:
        if pd.api.types.is_datetime64_any_dtype(d[c]):
            d[c] = d[c].dt.strftime("%Y-%m-%d")
    return f"const {name} = {d.to_json(orient='records', date_format='iso')};\n"


def write_all(tables, hourly_preds, qc=None):
    C.OUTPUT_DIR.mkdir(exist_ok=True)
    for fname, df in tables.items():
        df.to_csv(C.OUTPUT_DIR / f"{fname}.csv", index=False)
        if qc:
            qc.info(f"wrote {fname}.csv rows={len(df):,}")
    if hourly_preds is not None:
        hourly_preds.to_csv(C.OUTPUT_DIR / "predictions_hourly.csv", index=False)
        if qc:
            qc.info(f"wrote predictions_hourly.csv rows={len(hourly_preds):,}")

    # data.js: small tables for instant map load (§7.2).
    js_map = {"STATIONS": "stations", "PREDICTIONS": "predictions_window",
              "METRICS": "metrics", "ROUTES": "routes", "WEATHER_EFFECT": "weather_effect"}
    parts = ["// Auto-generated by export.py. Double-click safe (no fetch/CORS).\n"]
    for const, key in js_map.items():
        if key in tables:
            parts.append(_to_js(const, tables[key]))
    (C.OUTPUT_DIR / "data.js").write_text("".join(parts), encoding="utf-8")
    # profiles + hourly are large -> separate files.
    if "profiles" in tables:
        (C.OUTPUT_DIR / "data_profiles.js").write_text(_to_js("PROFILES", tables["profiles"]), encoding="utf-8")
    if hourly_preds is not None:
        (C.OUTPUT_DIR / "data_hourly.js").write_text(_to_js("HOURLY", hourly_preds), encoding="utf-8")
    if qc:
        qc.info("wrote data.js, data_profiles.js, data_hourly.js")
